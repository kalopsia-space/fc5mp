# gen_version_def.py — emit a .def that re-exports version.dll's symbols as
# forwarders to version_real.dll. Usage: python gen_version_def.py <real version.dll> <out.def>
import sys, pefile
pe = pefile.PE(sys.argv[1], fast_load=True)
pe.parse_data_directories(directories=[pefile.DIRECTORY_ENTRY['IMAGE_DIRECTORY_ENTRY_EXPORT']])
names = [e.name.decode() for e in pe.DIRECTORY_ENTRY_EXPORT.symbols if e.name]
with open(sys.argv[2], "w") as f:
    f.write("; generated by gen_version_def.py — forwarders to version_real.dll\n")
    f.write("LIBRARY version\nEXPORTS\n")
    for n in names:
        f.write(f"    {n}=version_real.{n}\n")
print(f"wrote {len(names)} forwarders")
